/**
 * The CATCC kit as SVG, for Figma on any plan (figma/catcc-kit/svg): a pure conversion of kit.json's node
 * trees, no browser. One file per specimen (parts/) and one sheet of the whole kit laid out by section
 * (CATCC Kit.svg). Written the way Figma's own SVG export writes things, which its SVG import reads back:
 *   - every layer is a <g id="…"> named like the component ("Control/Tool button", variant "state=on");
 *   - text is real <text> with Saira / IBM Plex Mono, weight, size, letter spacing (em) and fill, one <tspan x y>
 *     per line on its baseline, so it imports as editable text;
 *   - boxes are <rect> with their radius, fill and border (strokes inset as CSS borders are);
 *   - the scope graphics' SVG is inlined as groups (no nested <svg>, no ids to collide).
 * Not carried: auto layout, variants as Figma properties, variables, text styles, shadows (the dev plugin does those).
 * Shared by the generators (scripts/catcc/figma-kit.gen.ts, scripts/catcc/figma-kit-svg.ts) and the test.
 */
import fs from 'node:fs';
import path from 'node:path';

export interface Col {
  c: string;
  a: number;
}
export interface KitNode {
  t: 'frame' | 'text' | 'svg';
  n: string;
  x: number;
  y: number;
  w: number;
  h: number;
  kids?: KitNode[];
  fill?: Col;
  stroke?: { c: string; a: number; w: number | number[]; dash?: number[] };
  r?: number | number[];
  op?: number;
  clip?: boolean;
  // text
  s?: string;
  f?: string;
  wt?: number;
  sz?: number;
  ls?: number;
  col?: Col | null;
  up?: boolean;
  it?: boolean;
  ul?: boolean;
  cy?: number;
  /** where the first glyph starts, right of x (a leading space, or a run inside a truncating box) */
  gx?: number;
  /** the baseline below y (of the first line) */
  by?: number;
  /** a wrapped text's lines: start and baseline from (x, y) */
  lines?: { s: string; dx: number; dy: number }[];
  vis?: string;
  // svg
  svg?: string;
}
export interface Specimen {
  section: string;
  sectionTitle: string;
  name: string;
  variant: string;
  node: KitNode;
}
export interface Kit {
  tokens: { colors: { name: string; value: string; use?: string }[]; text: { name: string; family: string; weight: number; size: number; tracking?: number; color: string; sample: string; upper?: boolean }[] };
  sections: { id: string; title: string }[];
  specimens: Specimen[];
}

export const SVG_HEADER = '<!-- GENERATED by `node scripts/catcc/figma-kit-svg.ts` from figma/catcc-kit/kit.json - do not edit -->';
export const SHEET = 'CATCC Kit.svg';

const n2 = (v: number) => String(Math.round(v * 100) / 100);
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const attrs = (a: Record<string, string | number | undefined>) =>
  Object.entries(a)
    .filter(([, v]) => v !== undefined && v !== '')
    .map(([k, v]) => ` ${k}="${typeof v === 'number' ? n2(v) : esc(String(v))}"`)
    .join('');
const translate = (x: number, y: number) => (Math.abs(x) < 0.005 && Math.abs(y) < 0.005 ? undefined : `translate(${n2(x)} ${n2(y)})`);
const alpha = (a: number) => (a >= 0.9995 ? undefined : Math.round(a * 1000) / 1000);

/** css colour → [#RRGGBB, alpha] */
export function splitColor(v: string): [string, number] {
  const s = v.trim();
  if (/^#[0-9a-f]{6}$/i.test(s)) return [s.toUpperCase(), 1];
  const m = /^rgba?\(([^)]+)\)$/i.exec(s);
  if (!m) throw new Error(`not a colour: ${v}`);
  const p = m[1].split(/[\s,/]+/).filter(Boolean);
  const h = (x: string) => Math.round(parseFloat(x)).toString(16).padStart(2, '0');
  return [`#${h(p[0])}${h(p[1])}${h(p[2])}`.toUpperCase(), p.length > 3 ? parseFloat(p[3]) : 1];
}

/** a rounded rectangle with four radii as a path */
function roundedPath(x: number, y: number, w: number, h: number, r: number[]) {
  const [a, b, c, d] = r.map((q) => Math.max(0, Math.min(q, w / 2, h / 2)));
  return `M${n2(x + a)} ${n2(y)}H${n2(x + w - b)}A${n2(b)} ${n2(b)} 0 0 1 ${n2(x + w)} ${n2(y + b)}V${n2(y + h - c)}A${n2(c)} ${n2(c)} 0 0 1 ${n2(x + w - c)} ${n2(y + h)}H${n2(x + d)}A${n2(d)} ${n2(d)} 0 0 1 ${n2(x)} ${n2(y + h - d)}V${n2(y + a)}A${n2(a)} ${n2(a)} 0 0 1 ${n2(x + a)} ${n2(y)}Z`;
}

/** a frame's own box: fill, border (inside, as CSS draws it) */
function boxOf(n: KitNode): string {
  const out: string[] = [];
  const rr = Array.isArray(n.r) ? n.r : [n.r ?? 0, n.r ?? 0, n.r ?? 0, n.r ?? 0];
  const uniformR = rr.every((q) => q === rr[0]);
  const st = n.stroke;
  const sw = st && !Array.isArray(st.w) ? st.w : 0;
  const shape = (id: string, inset: number, paint: Record<string, string | number | undefined>) => {
    const x = inset,
      y = inset,
      w = Math.max(0, n.w - 2 * inset),
      h = Math.max(0, n.h - 2 * inset);
    if (uniformR) return `<rect${attrs({ id, x: x || undefined, y: y || undefined, width: w, height: h, rx: rr[0] ? Math.max(0, rr[0] - inset) : undefined, ...paint })}/>`;
    return `<path${attrs({ id, d: roundedPath(x, y, w, h, rr.map((q) => Math.max(0, q - inset))), ...paint })}/>`;
  };
  const strokePaint = st ? { stroke: st.c, 'stroke-opacity': alpha(st.a), 'stroke-width': sw, 'stroke-dasharray': st.dash ? st.dash.map(n2).join(' ') : undefined } : {};
  if (n.fill && st && sw) out.push(shape('box', sw / 2, { fill: n.fill.c, 'fill-opacity': alpha(n.fill.a), ...strokePaint }));
  else {
    if (n.fill) out.push(shape('fill', 0, { fill: n.fill.c, 'fill-opacity': alpha(n.fill.a) }));
    if (st && sw) out.push(shape('border', sw / 2, { fill: 'none', ...strokePaint }));
  }
  if (st && Array.isArray(st.w)) {
    // borders on some sides only: a strip per side
    const [t, r, b, l] = st.w;
    const p = { fill: st.c, 'fill-opacity': alpha(st.a) };
    if (t) out.push(`<rect${attrs({ id: 'border-top', width: n.w, height: t, ...p })}/>`);
    if (b) out.push(`<rect${attrs({ id: 'border-bottom', y: n.h - b, width: n.w, height: b, ...p })}/>`);
    if (l) out.push(`<rect${attrs({ id: 'border-left', width: l, height: n.h, ...p })}/>`);
    if (r) out.push(`<rect${attrs({ id: 'border-right', x: n.w - r, width: r, height: n.h, ...p })}/>`);
  }
  return out.join('');
}

/** a text spec as <text> with a <tspan> per line on its baseline (Figma's own export format) */
export function textOf(n: KitNode): string {
  const sz = n.sz ?? 12;
  const up = (s: string) => (n.up ? s.toUpperCase() : s);
  // the baseline: measured by the browser, else (older kit.json) a little under the line's centre
  const by = n.by ?? (n.cy !== undefined ? n.cy - n.y : n.h / 2) + sz * 0.3;
  const lines = n.lines?.length ? n.lines.map((l) => ({ s: l.s, x: n.x + l.dx, bl: n.y + l.dy })) : [{ s: n.vis ?? n.s ?? '', x: n.x + (n.gx ?? 0), bl: n.y + by }];
  const ls = n.ls ? Math.round((n.ls / sz) * 10000) / 10000 : 0;
  const col = n.col ?? { c: '#E6EDF3', a: 1 };
  const a = attrs({
    id: n.n,
    fill: col.c,
    'fill-opacity': alpha(col.a),
    'xml:space': 'preserve',
    style: 'white-space: pre',
    'font-family': n.f,
    'font-size': sz,
    'font-weight': n.wt ?? 400,
    'font-style': n.it ? 'italic' : undefined,
    'letter-spacing': ls ? `${ls}em` : '0em',
    'text-decoration': n.ul ? 'underline' : undefined,
  });
  return `<text${a}>${lines.map((l) => `<tspan${attrs({ x: l.x, y: l.bl })}>${esc(up(l.s))}</tspan>`).join('')}</text>`;
}

// clip paths are numbered per document (reset by each file), so the files are stable and ids never collide
let clipSeq = 0;

/** does an SVG's drawing reach past its viewBox (circles, lines, rects; paths are not measured) */
export function overflowsViewBox(inner: string, vb: number[]): boolean {
  const [x0, y0, w, h] = vb;
  const out = (x: number, y: number) => x < x0 - 1 || y < y0 - 1 || x > x0 + w + 1 || y > y0 + h + 1;
  const num = (tag: string, k: string) => Number((new RegExp(` ${k}="(-?[0-9.]+)"`).exec(tag) ?? [])[1] ?? 0);
  for (const m of inner.matchAll(/<(circle|line|rect)(?=[ />])[^>]*>/g)) {
    const t = m[0];
    if (/ transform="/.test(t)) continue;
    if (m[1] === 'circle') {
      const cx = num(t, 'cx'),
        cy = num(t, 'cy'),
        r = num(t, 'r');
      if (out(cx - r, cy - r) || out(cx + r, cy + r)) return true;
    } else if (m[1] === 'line') {
      if (out(num(t, 'x1'), num(t, 'y1')) || out(num(t, 'x2'), num(t, 'y2'))) return true;
    } else if (out(num(t, 'x'), num(t, 'y')) || out(num(t, 'x') + num(t, 'width'), num(t, 'y') + num(t, 'height'))) return true;
  }
  return false;
}

/** an inline SVG of the kit (a scope ring, a symbol, an icon) as a group placed and scaled like the browser drew it */
export function svgOf(n: KitNode): string {
  const src = n.svg ?? '';
  const m = /^<svg([^>]*)>([\s\S]*)<\/svg>$/.exec(src);
  if (!m) throw new Error(`${n.n}: not an inline SVG`);
  const root = Object.fromEntries([...m[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
  const inner = m[2].replace(/ (aria-hidden|aria-label|role)="[^"]*"/g, '');
  const at = translate(n.x, n.y);
  let fit = ''; // viewBox → box
  const vb = root.viewBox?.split(/[\s,]+/).map(Number);
  if (vb && vb.length === 4 && vb[2] > 0 && vb[3] > 0) {
    const sx = n.w / vb[2],
      sy = n.h / vb[3];
    const par = root.preserveAspectRatio ?? 'xMidYMid meet';
    let kx = sx,
      ky = sy,
      dx = 0,
      dy = 0;
    if (!par.startsWith('none')) {
      const k = par.includes('slice') ? Math.max(sx, sy) : Math.min(sx, sy);
      kx = ky = k;
      const fx = par.includes('xMin') ? 0 : par.includes('xMax') ? 1 : 0.5;
      const fy = par.includes('YMin') ? 0 : par.includes('YMax') ? 1 : 0.5;
      dx = (n.w - vb[2] * k) * fx;
      dy = (n.h - vb[3] * k) * fy;
    }
    const parts = [translate(dx, dy), Math.abs(kx - 1) > 1e-6 || Math.abs(ky - 1) > 1e-6 ? `scale(${Math.round(kx * 1e5) / 1e5}${kx === ky ? '' : ` ${Math.round(ky * 1e5) / 1e5}`})` : undefined, translate(-vb[0], -vb[1])].filter(Boolean);
    fit = parts.join(' ');
  }
  const inherit: Record<string, string> = {};
  for (const k of ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']) if (root[k] && !root[k].includes('currentColor')) inherit[k] = root[k];
  // clipped to its box where the browser clipped it and something reaches past it (the scope's outer rings)
  if (n.clip && vb && vb.length === 4 && overflowsViewBox(inner, vb)) {
    const cid = `clip${++clipSeq}`;
    return `<g${attrs({ id: n.n, transform: at })}><g${attrs({ id: 'clip', 'clip-path': `url(#${cid})` })}><g${attrs({ id: 'drawing', transform: fit || undefined, ...inherit })}>${inner}</g></g><defs><clipPath${attrs({ id: cid })}><rect${attrs({ width: n.w, height: n.h })}/></clipPath></defs></g>`;
  }
  return `<g${attrs({ id: n.n, transform: [at, fit].filter(Boolean).join(' ') || undefined, ...inherit })}>${inner}</g>`;
}

const outside = (n: KitNode, k: KitNode) => k.x < -0.5 || k.y < -0.5 || k.x + k.w > n.w + 0.5 || k.y + k.h > n.h + 0.5;

/** a node and its children; `id` overrides the layer name (a specimen's root is named for the component) */
export function nodeOf(n: KitNode, id?: string, place = true): string {
  if (n.t === 'text') return textOf(id ? { ...n, n: id } : n);
  if (n.t === 'svg') return svgOf({ ...n, n: id ?? n.n, x: place ? n.x : 0, y: place ? n.y : 0 });
  let kids = (n.kids ?? []).map((k) => nodeOf(k)).join('');
  // a box that hides what overflows it (a scrolling sidebar): clipped only when something does overflow
  // an SVG with its lettering (serialize.js puts the <text>s beside the drawing in a frame): clipped as the SVG is
  const k0 = n.kids?.[0];
  const svgClip = !!k0 && k0.t === 'svg' && !!k0.clip && Math.abs(k0.x) < 0.5 && Math.abs(k0.y) < 0.5 && Math.abs(k0.w - n.w) < 0.5 && Math.abs(k0.h - n.h) < 0.5;
  if ((n.clip || svgClip) && (n.kids ?? []).some((k) => outside(n, k))) {
    const cid = `clip${++clipSeq}`;
    const r = Array.isArray(n.r) ? undefined : n.r;
    kids = `<g${attrs({ id: 'clip', 'clip-path': `url(#${cid})` })}>${kids}</g><defs><clipPath${attrs({ id: cid })}><rect${attrs({ width: n.w, height: n.h, rx: r || undefined })}/></clipPath></defs>`;
  }
  return `<g${attrs({ id: id ?? n.n, transform: place ? translate(n.x, n.y) : undefined, opacity: n.op !== undefined && n.op < 1 ? n.op : undefined })}>${boxOf(n)}${kids}</g>`;
}

const svgDoc = (w: number, h: number, body: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg"${attrs({ width: Math.ceil(w), height: Math.ceil(h), viewBox: `0 0 ${Math.ceil(w)} ${Math.ceil(h)}`, fill: 'none' })}>\n${SVG_HEADER}\n${body}\n</svg>\n`;

/** a specimen's layer name: "Control/Tool button / state=on" (or just the name when it has no variant) */
export const specimenLabel = (s: Specimen) => (s.variant ? `${s.name} / ${s.variant}` : s.name);

/** a specimen's file under svg/parts: "Control - Tool button - state=on.svg" (Windows-safe) */
export function specimenFile(s: Specimen): string {
  const safe = (x: string) => x.replace(/\//g, ' - ').replace(/[<>:"\\|?*]/g, '_');
  return `parts/${safe(s.name)}${s.variant ? ` - ${safe(s.variant)}` : ''}.svg`;
}

// ---------------------------------------------------------------- the sheet

const BG = '#0E1116';
const LABEL = { f: 'IBM Plex Mono', wt: 500, sz: 11, ls: 0.66, col: { c: '#93A1B0', a: 1 } };
const TITLE = { f: 'Saira', wt: 600, sz: 22, ls: 1.32, col: { c: '#E6EDF3', a: 1 } };
const label = (id: string, s: string, x: number, y: number, st: typeof LABEL, up = false) => textOf({ t: 'text', n: id, s, x, y, w: 0, h: 0, by: st.sz * 0.8, up, ...st });

/** lays boxes left to right, wrapping at `maxW`: positions and the total size */
function flow(sizes: { w: number; h: number }[], maxW: number, gapX: number, gapY: number) {
  const pos: { x: number; y: number }[] = [];
  let x = 0,
    y = 0,
    rowH = 0,
    W = 0;
  for (const s of sizes) {
    if (x > 0 && x + s.w > maxW) {
      x = 0;
      y += rowH + gapY;
      rowH = 0;
    }
    pos.push({ x, y });
    x += s.w + gapX;
    rowH = Math.max(rowH, s.h);
    W = Math.max(W, x - gapX);
  }
  return { pos, w: W, h: y + rowH };
}

const SHEET_W = 1760;
const PAD = 64;

/**
 * The whole kit on one sheet: Tokens (colour swatches, type), then a group per section ("Section/Controls")
 * holding a group per component ("Control/Tool button") with its variants as layers ("state=on"), each with a
 * caption beside the group ("Control/Tool button" label) so selecting the variants never picks up the caption.
 */
export function sheetSvg(kit: Kit): string {
  clipSeq = 0;
  const blocks: { w: number; h: number; body: (x: number, y: number) => string }[] = [];

  // tokens: swatches and type samples
  {
    const sw = kit.tokens.colors.map((c) => ({ w: 150, h: 78, c }));
    const sf = flow(sw, SHEET_W, 16, 16);
    const swatches = (ox: number, oy: number) =>
      `<g${attrs({ id: 'Colors', transform: translate(ox, oy) })}>${sw
        .map((s, i) => {
          const [hex, a] = splitColor(s.c.value);
          const p = sf.pos[i];
          return `<g${attrs({ id: s.c.name, transform: translate(p.x, p.y) })}><rect${attrs({ id: 'swatch', width: 150, height: 44, rx: 6, fill: hex, 'fill-opacity': alpha(a), stroke: '#374250', 'stroke-width': 1 })}/>${label('name', s.c.name, 0, 52, LABEL)}${label('value', s.c.value, 0, 66, { ...LABEL, wt: 400, col: { c: '#6B7683', a: 1 } })}</g>`;
        })
        .join('')}</g>`;
    const types = kit.tokens.text.map((t) => ({ t, h: Math.max(t.size * 1.4, 16) + 8 }));
    let ty = 0;
    const typeRows = types.map((r) => {
      const y = ty;
      ty += r.h;
      return { ...r, y };
    });
    const typeBlock = (ox: number, oy: number) =>
      `<g${attrs({ id: 'Text styles', transform: translate(ox, oy) })}>${typeRows
        .map((r) => {
          const [hex, a] = splitColor(r.t.color);
          const sample = textOf({ t: 'text', n: r.t.name, s: r.t.sample, x: 260, y: r.y, w: 0, h: 0, by: r.t.size, f: r.t.family, wt: r.t.weight, sz: r.t.size, ls: (r.t.tracking ?? 0) * r.t.size, up: r.t.upper, col: { c: hex, a } });
          return `${label(`${r.t.name} label`, `${r.t.name} · ${r.t.family} ${r.t.weight} ${r.t.size}`, 0, r.y + Math.max(0, r.t.size - 11), LABEL)}${sample}`;
        })
        .join('')}</g>`;
    const h = 40 + sf.h + 40 + ty;
    blocks.push({
      w: SHEET_W,
      h,
      body: (x, y) => `<g${attrs({ id: 'Section/Tokens', transform: translate(x, y) })}>${label('title', 'Tokens', 0, 0, TITLE, true)}${swatches(0, 40)}${typeBlock(0, 40 + sf.h + 40)}</g>`,
    });
  }

  // a section per kit section, a group per component
  const secs: { id: string; title: string; groups: { name: string; items: Specimen[] }[] }[] = [];
  for (const s of kit.sections) secs.push({ ...s, groups: [] });
  for (const sp of kit.specimens) {
    let sec = secs.find((s) => s.id === sp.section);
    if (!sec) secs.push((sec = { id: sp.section, title: sp.sectionTitle || sp.section, groups: [] }));
    let g = sec.groups.find((x) => x.name === sp.name);
    if (!g) sec.groups.push((g = { name: sp.name, items: [] }));
    g.items.push(sp);
  }
  for (const sec of secs.filter((s) => s.groups.length)) {
    const groups = sec.groups.map((g) => {
      const f = flow(
        g.items.map((s) => s.node),
        SHEET_W,
        16,
        16,
      );
      const single = g.items.length === 1 && !g.items[0].variant;
      const body = (ox: number, oy: number) => {
        const caption = label(`${g.name} label`, g.name, ox, oy, LABEL);
        const at = (i: number) => translate(f.pos[i].x, f.pos[i].y);
        if (single) return caption + `<g${attrs({ id: g.name, transform: translate(ox, oy + 22) })}>${nodeOf(g.items[0].node, undefined, false)}</g>`;
        const vs = g.items.map((s, i) => `<g${attrs({ id: s.variant || `variant=v${i + 1}`, transform: at(i) })}>${nodeOf(s.node, undefined, false)}</g>`).join('');
        return caption + `<g${attrs({ id: g.name, transform: translate(ox, oy + 22) })}>${vs}</g>`;
      };
      return { w: Math.max(f.w, 140), h: f.h + 22, body };
    });
    const gf = flow(groups, SHEET_W, 48, 40);
    blocks.push({
      w: SHEET_W,
      h: 40 + gf.h,
      body: (x, y) => `<g${attrs({ id: `Section/${sec.title}`, transform: translate(x, y) })}>${label('title', sec.title, 0, 0, TITLE, true)}${groups.map((g, i) => g.body(gf.pos[i].x, 40 + gf.pos[i].y)).join('')}</g>`,
    });
  }

  let y = PAD;
  const parts = blocks.map((b) => {
    const s = b.body(PAD, y);
    y += b.h + 80;
    return s;
  });
  const H = y - 80 + PAD;
  return svgDoc(SHEET_W + 2 * PAD, H, `<rect${attrs({ id: 'Background', width: SHEET_W + 2 * PAD, height: Math.ceil(H), fill: BG })}/>\n${parts.join('\n')}`);
}

/** one specimen on its own: the root layer is named "Control/Tool button / state=on" */
export function specimenSvg(s: Specimen): string {
  clipSeq = 0;
  return svgDoc(s.node.w, s.node.h, nodeOf(s.node, specimenLabel(s), false));
}

/** every file of figma/catcc-kit/svg, path (relative, forward slashes) → contents */
export function kitSvgFiles(kit: Kit): Map<string, string> {
  const files = new Map<string, string>();
  files.set(SHEET, sheetSvg(kit));
  for (const s of kit.specimens) {
    const p = specimenFile(s);
    if (files.has(p)) throw new Error(`two specimens write ${p}`);
    files.set(p, specimenSvg(s));
  }
  return files;
}

/** writes figma/catcc-kit/svg from a kit, removing SVGs no specimen writes any more; returns the total size in bytes */
export function writeKitSvg(dir: string, kit: Kit): number {
  const files = kitSvgFiles(kit);
  for (const sub of ['', 'parts']) {
    const d = path.join(dir, sub);
    if (!fs.existsSync(d)) continue;
    for (const f of fs.readdirSync(d)) if (f.endsWith('.svg') && !files.has(sub ? `${sub}/${f}` : f)) fs.rmSync(path.join(d, f));
  }
  let bytes = 0;
  for (const [p, text] of files) {
    const full = path.join(dir, p);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text);
    bytes += Buffer.byteLength(text);
  }
  return bytes;
}
