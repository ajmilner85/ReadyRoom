/**
 * The Figma plugin's code.js: the kit's data (kit.json) as a `KIT` constant, then the plugin source
 * (figma/catcc-kit/plugin.cjs). A Figma plugin's main file is one script with no imports, so the data rides in it.
 * Shared by the generator (scripts/catcc/figma-kit.gen.ts) and its test.
 */
export const CODE_HEADER = '// GENERATED by `node scripts/catcc/figma-kit.gen.ts` from figma/catcc-kit/plugin.cjs and kit.json - do not edit\n';

export function assembleCode(pluginSrc: string, kitJson: string): string {
  const lf = (s: string) => s.replace(/\r\n/g, '\n');
  return `${CODE_HEADER}var KIT = ${lf(kitJson).trim()};\n\n${lf(pluginSrc)}`;
}

/** kit.json text: one specimen per line, so a change to one component is a one-line diff */
export function formatKit(kit: { specimens: unknown[] } & Record<string, unknown>): string {
  const { specimens, ...head } = kit;
  const top = JSON.stringify(head, null, 2).replace(/\n}$/, '');
  return `${top},\n  "specimens": [\n${specimens.map((s) => `    ${JSON.stringify(s)}`).join(',\n')}\n  ]\n}\n`;
}
