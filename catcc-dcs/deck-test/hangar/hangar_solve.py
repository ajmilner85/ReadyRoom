"""The hangar's tows, solved for the user's layout in his own order: runs hangar_solve.lua in the test rig and writes
what it finds to hangar-tows.lua, which hangar_plan.py puts into the plan the demo runs with (crewtest_hangar.lua).

    1. the test harness written to a folder (once; see ../crew-test/luarun.py):
         set CATCC_LUA_DUMP=<folder>   then   npx vitest run catcc-dcs/test/crewtest.test.ts -t "ten items"
    2. python -I hangar_plan.py                 (the plan from the drawing: the places, the grid, the tractors)
    3. python -I hangar_solve.py <folder>       (some six minutes: every aircraft's tow and the tractors' ways; says which could not be solved)
    4. python -I hangar_plan.py                 (the plan again, now with the tows)

Needs DCS installed (its own Lua 5.1: bin-mt/lua.dll). hangar_solve.lua says what is searched and against what.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'hangar-tows.lua')


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    args = [sys.executable, '-I', os.path.join(HERE, '..', 'crew-test', 'luarun.py'), sys.argv[1], os.path.join(HERE, 'hangar_solve.lua'), 'DEMO_ON=true', 'UI_ON=true', 'CATCC_DEMO_NO_TOWS=true'] + sys.argv[2:]
    r = subprocess.run(args, capture_output=True, text=True, encoding='utf-8', errors='replace')
    lines = r.stdout.splitlines()
    bad = [ln for ln in lines if ln.startswith('ERROR') or ln.startswith('FAIL ')]
    slots = [re.match(r'SLOT (\d+) (-?[\d.]+) (-?[\d.]+) (-?[\d.]+)', ln) for ln in lines]
    slots = [m for m in slots if m]
    tows = [ln[4:] for ln in lines if ln.startswith('TOW ')]
    posts = [re.match(r'POST (\d+) (-?[\d.]+) (-?[\d.]+) (-?\d+)', ln) for ln in lines]
    posts = [m for m in posts if m]
    hops = [ln[4:] for ln in lines if ln.startswith('HOP ')]
    clear = [ln[6:] for ln in lines if ln.startswith('CLEAR [')]
    post_clash = [ln[10:] for ln in lines if ln.startswith('POSTCLASH [')]
    for ln in lines:
        if ln.startswith('CLEARPAIRS'):
            print(ln)
    done = [ln for ln in lines if ln.startswith('DONE')]
    for ln in bad + done:
        print(ln[:1500])
    if not done:
        print(r.stdout[-3000:], r.stderr[-3000:])
        raise SystemExit('the solver did not finish')
    if any(a.startswith('ONLY=') or a.startswith('DIAG=') for a in sys.argv[2:]):
        for t in tows:
            print(t[:700])
        print('(a part of it only: hangar-tows.lua is not written)')
        return
    L = ['-- GENERATED by catcc-dcs/deck-test/hangar/hangar_solve.py (hangar_solve.lua, in the test rig). Do not edit.',
         '-- The tow of every aircraft of the user\'s hangar plan onto its place on its elevator, in his own order: each can be driven',
         '-- with everything that is still down there at its turn. By the plan\'s place (n). hangar_solve.lua says what the fields are.',
         'return {',
         '  -- where each place was when its tow was solved (x forward, z to starboard, its heading in degrees): hangar_plan.py takes the',
         '  -- tows only if the drawing still has every aircraft there',
         '  layout = { %s },' % ', '.join('[%s] = { %s, %s, %s }' % m.groups() for m in slots),
         '  -- the places a tractor waits at (the homes of the plan, then its rest), and which way it stands there (1: nose forward; -1: aft):',
         '  -- the way it can drive in',
         '  posts = { %s },' % ', '.join('{ %s, %s, %s }' % m.groups()[1:] for m in posts),
         '  tows = {']
    for t in tows:
        body, _, note = t.partition(' -- ')
        n = re.match(r'n = (\d+), ', body).group(1)
        L.append('    [%s] = { %s }, -- %s' % (n, body[len('n = %s, ' % n):], note))
    L += ['  },',
          '  -- a tractor\'s ways from post to post, with the hangar as it is packed: [from] = { [to] = { side, back, pts } }',
          '  hops = {']
    L += ['    ' + h for h in hops]
    L += ['  },',
          '  -- which tows can be driven at the same time: by place, the places whose tows keep 0.6 m from its own all along both',
          '  clear = {']
    L += ['    ' + c for c in clear]
    L += ['  },',
          '  -- by post: the places whose tows pass through a tractor waiting at that post',
          '  postClash = {']
    L += ['    ' + c for c in post_clash]
    L += ['  },', '}']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('%d tows written to %s%s' % (len(tows), os.path.normpath(OUT), '' if not bad else '; %d NOT SOLVED' % len([b for b in bad if b.startswith('FAIL')])))


if __name__ == '__main__':
    main()
